# 15 ------------------------------------------------------------------------
b.h("15. Why it chooses from 12 designs, and what comes next")
b.p("**Why a fixed set of 12 (the project plan chose this on purpose):**")
b.bullets([
    "**Safety:** the AI never writes or runs new code.",
    "**Proof:** with fixed options we can prove whether the agent is smart, by comparing it with random choices, a person and trying all 12. With unlimited options there is no fair way to measure that.",
    "**A small AI:** qwen 3B already invents designs that do not exist, writes some poor descriptions and gives some wrong advice; with complete freedom it would likely build worse pipelines.",
    "**Too little data to judge:** 100 practice sentences are too few to trust an open-ended design.",
])
b.p("**What comes next: A3, \"choose, then refine\" (decision 45).** After the current work, the agent will start from "
    "the best of the 12 and then **rewrite its own note** for the project, using its mistakes: write its own "
    "instructions, rewrite descriptions it keeps getting wrong, add rules against extracting extra words, change how many "
    "examples it shows. Each change is tested and kept only if the score improves. It still never writes code, so it "
    "stays safe and measurable, but the pipeline becomes personalised to the project. A rule for keeping or dropping A3 "
    "will be fixed before building it, and A1, A2 and A3 will all be reported on the locked test data.")
